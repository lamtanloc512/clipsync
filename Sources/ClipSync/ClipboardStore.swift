import AppKit
import ImageIO
import UniformTypeIdentifiers

struct ClipItem {
    enum Kind: String { case text, image }

    let kind: Kind
    let text: String?
    /// PNG data for image items.
    let image: Data?
    /// "Mac" or the name of the phone that sent it.
    let source: String
    /// Paired-device id of the phone that sent it; nil for copies made on the Mac.
    var sourceID: String? = nil
    let date: Date

    var preview: String {
        switch kind {
        case .image:
            return "🖼 Image (\(ByteCountFormatter.string(fromByteCount: Int64(image?.count ?? 0), countStyle: .file)))"
        case .text:
            let oneLine = (text ?? "")
                .replacingOccurrences(of: "\n", with: " ")
                .trimmingCharacters(in: .whitespaces)
            return oneLine.count > 48 ? String(oneLine.prefix(48)) + "…" : oneLine
        }
    }
}

/// Watches the macOS pasteboard and lets the server read/write it.
/// Every change (local copy or remote push) bumps `version`, which clients long-poll on.
final class ClipboardStore {
    private let pasteboard = NSPasteboard.general
    private var lastChangeCount: Int
    private var timer: Timer?
    private var waiters: [UUID: () -> Void] = [:]

    private(set) var version = 0
    private(set) var current: ClipItem?
    private(set) var history: [ClipItem] = []
    let maxHistory = 20

    /// Called on the main queue whenever the clipboard changes.
    var onChange: ((ClipItem) -> Void)?

    /// Markers password managers and similar apps put on copies that must not leave the Mac
    /// (nspasteboard.org conventions plus older vendor-specific ones).
    private static let privateTypes = Set([
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
    ].map { NSPasteboard.PasteboardType($0) })

    enum ImageResult { case ok, tooLarge, unsupported }
    static let maxImagePixels = 50_000_000
    private static let allowedImageTypes: Set<String> = [
        UTType.png.identifier, UTType.jpeg.identifier, UTType.heic.identifier, UTType.heif.identifier,
    ]

    init() {
        lastChangeCount = pasteboard.changeCount
        if let item = readPasteboard() {
            current = item
            version = 1
        }
    }

    func start() {
        timer = scheduleTimer(after: 0.5, repeats: true) { [weak self] _ in
            self?.poll()
        }
    }

    // MARK: - Reading

    private func poll() {
        let changeCount = pasteboard.changeCount
        guard changeCount != lastChangeCount else { return }
        lastChangeCount = changeCount
        guard let item = readPasteboard() else { return }
        commit(item)
    }

    private func readPasteboard() -> ClipItem? {
        let types = pasteboard.types ?? []
        // Respect password managers that mark their copies as concealed/transient.
        if types.contains(where: Self.privateTypes.contains) { return nil }

        if let text = pasteboard.string(forType: .string), !text.isEmpty {
            return ClipItem(kind: .text, text: text, image: nil, source: "Mac", date: Date())
        }
        if let png = pasteboard.data(forType: .png) {
            return ClipItem(kind: .image, text: nil, image: png, source: "Mac", date: Date())
        }
        if let tiff = pasteboard.data(forType: .tiff),
           let rep = NSBitmapImageRep(data: tiff),
           let png = rep.representation(using: .png, properties: [:]) {
            return ClipItem(kind: .image, text: nil, image: png, source: "Mac", date: Date())
        }
        return nil
    }

    // MARK: - Writing

    func setText(_ text: String, source: String, sourceID: String? = nil) {
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
        lastChangeCount = pasteboard.changeCount
        commit(ClipItem(kind: .text, text: text, image: nil, source: source, sourceID: sourceID, date: Date()))
    }

    /// Accepts PNG / JPEG / HEIC only, and checks the pixel size before decoding anything,
    /// so a tiny file claiming to be 50 000 × 50 000 cannot exhaust memory.
    @discardableResult
    func setImage(_ data: Data, source: String, sourceID: String? = nil) -> ImageResult {
        guard let src = CGImageSourceCreateWithData(data as CFData, [kCGImageSourceShouldCache: false] as CFDictionary),
              let type = CGImageSourceGetType(src) as String?,
              Self.allowedImageTypes.contains(type),
              let props = CGImageSourceCopyPropertiesAtIndex(src, 0, nil) as? [CFString: Any],
              let width = props[kCGImagePropertyPixelWidth] as? Int,
              let height = props[kCGImagePropertyPixelHeight] as? Int else { return .unsupported }
        guard width > 0, height > 0, width * height <= Self.maxImagePixels else { return .tooLarge }
        guard let cgImage = CGImageSourceCreateImageAtIndex(src, 0, nil) else { return .unsupported }
        let rep = NSBitmapImageRep(cgImage: cgImage)
        guard let png = rep.representation(using: .png, properties: [:]),
              let image = NSImage(data: png) else { return .unsupported }
        pasteboard.clearContents()
        pasteboard.writeObjects([image])
        lastChangeCount = pasteboard.changeCount
        commit(ClipItem(kind: .image, text: nil, image: png, source: source, sourceID: sourceID, date: Date()))
        return .ok
    }

    /// Re-copies an item from history (from the menu).
    func restore(_ item: ClipItem) {
        switch item.kind {
        case .text: setText(item.text ?? "", source: item.source)
        case .image: if let data = item.image { setImage(data, source: item.source) }
        }
    }

    private func commit(_ item: ClipItem) {
        version += 1
        current = item
        history.removeAll { old in
            old.kind == .text && item.kind == .text && old.text == item.text
        }
        history.insert(item, at: 0)
        if history.count > maxHistory { history.removeLast(history.count - maxHistory) }

        let pending = waiters
        waiters.removeAll()
        pending.values.forEach { $0() }
        onChange?(item)
    }

    // MARK: - Long polling

    /// Calls `completion` as soon as `version > since`, or after `timeout` seconds.
    func waitForChange(since: Int, timeout: TimeInterval, completion: @escaping () -> Void) {
        if version > since {
            completion()
            return
        }
        let id = UUID()
        waiters[id] = completion
        scheduleTimer(after: timeout) { [weak self] _ in
            guard let self, let waiter = self.waiters.removeValue(forKey: id) else { return }
            waiter()
        }
    }
}
