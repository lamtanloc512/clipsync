// Builds the phone web client and embeds it into the app as
// Sources/ClipSync/WebAssets.generated.swift, so building the Mac app never needs Node.
//
//   cd web && npm ci && npm run build
//
// UI: Tailwind CSS v4 + Basecoat (https://github.com/lamtanloc512/basecoat), Lyra style pack,
// pinned to BASECOAT_COMMIT. Set BASECOAT_DIR to use a local checkout instead.

import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { gzipSync } from 'node:zlib';

const BASECOAT_REPO = 'https://github.com/lamtanloc512/basecoat.git';
const BASECOAT_COMMIT = 'fb97086a83ed20a5be7ee5fe4c5422ed9cfb3b6b';

const web = dirname(fileURLToPath(import.meta.url));
const cache = join(web, '.cache');
const output = resolve(web, '../Sources/ClipSync/WebAssets.generated.swift');
mkdirSync(cache, { recursive: true });

const git = (args, cwd) => execFileSync('git', args, { cwd, stdio: ['ignore', 'pipe', 'inherit'] }).toString().trim();
const headOf = (dir) => {
  try { return git(['rev-parse', 'HEAD'], dir); } catch { return ''; }
};

function basecoatCheckout() {
  if (process.env.BASECOAT_DIR) {
    const dir = resolve(process.env.BASECOAT_DIR);
    if (headOf(dir) !== BASECOAT_COMMIT) {
      console.warn(`warning: BASECOAT_DIR is not at the pinned commit ${BASECOAT_COMMIT}`);
    }
    return dir;
  }
  const dir = join(cache, `basecoat-${BASECOAT_COMMIT.slice(0, 12)}`);
  if (headOf(dir) === BASECOAT_COMMIT) return dir;
  if (!existsSync(join(dir, '.git'))) {
    mkdirSync(dir, { recursive: true });
    git(['init', '-q'], dir);
    git(['remote', 'add', 'origin', BASECOAT_REPO], dir);
  }
  git(['fetch', '-q', '--depth', '1', 'origin', BASECOAT_COMMIT], dir);
  git(['checkout', '-q', '--detach', 'FETCH_HEAD'], dir);
  return dir;
}

const basecoat = basecoatCheckout();

// --- CSS ---------------------------------------------------------------------
const cssInput = readFileSync(join(web, 'app.css'), 'utf8')
  .replace('BASECOAT/', `${basecoat.replaceAll('\\', '/')}/`)
  .replaceAll('@source "./', '@source "../');
writeFileSync(join(cache, 'app.input.css'), cssInput);
execFileSync(join(web, 'node_modules/.bin/tailwindcss'),
  ['-i', join(cache, 'app.input.css'), '-o', join(cache, 'app.css'), '--minify'],
  { stdio: 'inherit' });
// Normalised once, so the plain, gzip and Swift copies are byte-for-byte the same.
const normalize = (text) => text.replace(/\r\n/g, '\n').replace(/\n$/, '');
const css = normalize(readFileSync(join(cache, 'app.css'), 'utf8'));

// --- JS ----------------------------------------------------------------------
const vendor = ['basecoat.js', 'toast.js']
  .map((f) => `/* Basecoat ${f} (MIT) — ${BASECOAT_REPO} @ ${BASECOAT_COMMIT.slice(0, 7)} */\n` +
    readFileSync(join(basecoat, 'src/js', f), 'utf8'))
  .join('\n');
const js = normalize(`${vendor}\n/* ClipSync (GPL-3.0) */\n${readFileSync(join(web, 'app.js'), 'utf8')}`);

// --- HTML & static files -------------------------------------------------------
// Asset URLs carry a content hash. Bump ASSET_SALT to force phones to refetch unchanged content
// (2: v1.1.0 could cache a truncated stylesheet for a year).
const ASSET_SALT = '2';
const short = (s) => createHash('sha256').update(ASSET_SALT).update(s).digest('hex').slice(0, 12);
const html = readFileSync(join(web, 'index.html'), 'utf8')
  .replace('__CSS_VERSION__', short(css))
  .replace('__JS_VERSION__', short(js));
const manifest = readFileSync(join(web, 'manifest.webmanifest'), 'utf8');
// The service worker's version covers everything it caches, so any change ships a new worker.
const serviceWorker = readFileSync(join(web, 'sw.js'), 'utf8')
  .replace('__SW_VERSION__', short(html + css + js + manifest))
  .replace('__CSS_VERSION__', short(css))
  .replace('__JS_VERSION__', short(js));
const icon = readFileSync(join(web, 'icon.svg'), 'utf8');
// PNG icons (rendered from assets/AppIcon.svg by assets/make-icons.mjs), embedded as base64.
const pngIcons = ['icon-180.png', 'icon-192.png', 'icon-512.png', 'icon-maskable-512.png'];
const pngBase64 = Object.fromEntries(pngIcons.map((f) => [f, readFileSync(join(web, f)).toString('base64')]));

// --- Swift ---------------------------------------------------------------------
// Raw string literal whose delimiter cannot occur in (or interpolate into) the content.
function swiftString(content) {
  let hashes = '#';
  while (content.includes(`"""${hashes}`) || content.includes(`\\${hashes}`)) hashes += '#';
  return `${hashes}"""\n${content.replace(/\r\n/g, '\n').replace(/\n$/, '')}\n"""${hashes}`;
}

const swift = `// GENERATED by web/build.mjs — do not edit by hand. Run \`cd web && npm run build\`.
// UI built with Tailwind CSS v4 and Basecoat (MIT), ${BASECOAT_REPO} @ ${BASECOAT_COMMIT}, Lyra style pack.
// swiftlint:disable all

enum WebAssets {
    static let indexHTML = ${swiftString(html)}

    static let appCSS = ${swiftString(css)}

    static let appJS = ${swiftString(js)}

    /// Pre-compressed copies, served when the browser accepts gzip (~7x smaller).
    static let appCSSGzip = "${gzipSync(css, { level: 9 }).toString('base64')}"
    static let appJSGzip = "${gzipSync(js, { level: 9 }).toString('base64')}"
    static let cssVersion = "${short(css)}"
    static let jsVersion = "${short(js)}"

    static let manifest = ${swiftString(manifest)}

    static let serviceWorker = ${swiftString(serviceWorker)}

    static let iconSVG = ${swiftString(icon)}

    /// Path → base64 PNG.
    static let pngIcons: [String: String] = [
${pngIcons.map((f) => `        "/${f}": "${pngBase64[f]}",`).join('\n')}
    ]
}
`;
writeFileSync(output, swift);

// Plain files too, for previewing the client in a desktop browser.
const dist = join(cache, 'dist');
mkdirSync(dist, { recursive: true });
for (const [name, body] of Object.entries({ 'index.html': html, 'app.css': css, 'app.js': js,
  'manifest.webmanifest': manifest, 'icon.svg': icon, 'sw.js': serviceWorker })) {
  writeFileSync(join(dist, name), body);
}
for (const f of pngIcons) writeFileSync(join(dist, f), Buffer.from(pngBase64[f], 'base64'));
console.log(`wrote ${output} (css ${css.length} B, js ${js.length} B)`);
